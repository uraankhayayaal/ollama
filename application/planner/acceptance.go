package planner

import (
	"ai/domain"
)

// Acceptor — порт детерминированной приёмки собранного приложения.
// Реализуется инфраструктурный пакет acceptor (PlannerAdapter); оркестратор
// плана зависит только от этого интерфейса и отчёта domain.Report.
type Acceptor interface {
	// MaxRounds — бюджет циклов «приёмка → планировщик исправлений →
	// приёмка». 0 или меньше — цикл исправлений отключён.
	MaxRounds() int
	// Accept выполняет приёмку директории (сборка, запуск, формат, анализ,
	// ЛСП) и возвращает структурированный отчёт.
	Accept(dir string) *domain.Report
}
