// CallFunction диспетчеризует вызов модели к инструменту.
//
// Два защитных behaviours поверх tools.Set.Execute:
//
//  1. Ассистент НЕ ПИШЕТ файлы проекта. Инструментов правки в наборе нет, но
//     модель всё равно может позвать WriteFiles/SearchReplace/DeleteFiles/Run —
//     раньше это давало безликое «function X not in tool set», и модель
//     продолжала объявлять «правлю всё», ничего не делая. Теперь на такой вызов
//     возвращается явная подсказка маршрута: завести эпик (BoardCreateEpic).
//
//  2. Антизацикливание по инструментам: тот же вызов (инструмент + аргументы)
//     допускается limitedToolRepeats раз; дальше инструмент не выполняется, а
//     модели возвращается status=skipped с требованием закончить ход — ответить
//     пользователю или завести эпик. Это чинит реальный баг: на просьбу
//     «удали упоминания rust» ассистент объявлял правку и 6 раз подряд
//     перечитывал один и тот же ci.yml, пока сессия не умирала по таймауту.
func (a *Assistant) CallFunction(functionName string, functionArgs map[string]any) ([]byte, error) {
	if isProjectWriteTool(functionName) {
		return a.writeToolRefusal(functionName), nil
	}
	if !a.Tools.Has(functionName) {
		// Инструмента нет в наборе (например, доска не подключена) — повторная
		// попытка тем более ничего не даст: отдаём тот же отказ, что и выше.
		return a.writeToolRefusal(functionName), nil
	}
	sig := toolCallSignature(functionName, functionArgs)
	a.seenCalls[sig]++
	if a.seenCalls[sig] > limitedToolRepeats {
		return a.repeatCallResult(functionName, a.seenCalls[sig]), nil
	}
	return a.Tools.Execute(functionName, functionArgs)
}

// limitedToolRepeats — сколько раз ассистенту разрешено вызвать один и тот же
// инструмент с теми же аргументами в рамках одного хода. Два повтора обычно
// осмысленны (повторный дорез после уточнения диапазона строк), третий и
// последующие — почти всегда зацикливание.
const limitedToolRepeats = 2

// isProjectWriteTool — инструменты, изменяющие файлы проекта или выполняющие
// произвольные команды. Ассистент (собеседник в чате) ими не располагает:
// правку проекта делают агенты по задачам с доски.
func isProjectWriteTool(name string) bool {
	switch name {
	case "WriteFiles", "AppendFile", "DeleteFiles", "SearchReplace",
		"PatchGoFunction", "PatchFunction", "Run":
		return true
	}
	return false
}

// toolCallSignature — стабильный ключ вызова инструмента: имя +
// канонический JSON аргументов. Порядок ключей в map нормализован
// сортировкой (encoding/json сортирует ключи map), поэтому порядок полей в
// аргументах от модели на подпись не влияет.
func toolCallSignature(name string, args map[string]any) string {
	if len(args) == 0 {
		return name
	}
	b, err := json.Marshal(args)
	if err != nil {
		// Не сериализуется — считаем вызов уникальным, защита не срабатывает,
		// но и ломать нормальный вызов нельзя.
		return name + "|unserializable"
	}
	return name + "|" + string(b)
}

// writeToolRefusal — отказ на попытку правки файлов проекта: не ошибка
// (иначе модель воспримет это как сбой и попробует другой инструмент), а
// status=skipped с явным маршрутом «BoardCreateEpic».
func (a *Assistant) writeToolRefusal(name string) []byte {
	data, _ := json.Marshal(map[string]any{
		"status": "skipped",
		"tool":   name,
		"message": fmt.Sprintf("Инструмент %s недоступен ассистенту: файлы проекта ассистент не правит — "+
			"это делают агенты по задачам с доски. Не пытайся править файлы и не объявляй правку вслух. "+
			"Маршрут: вызови BoardCreateEpic (task_id, title, description) — задача попадёт на доску, "+
			"её разберёт и выполнит Системный архитектор с лидами направлений. Если пользователь просил "+
			"выполнить правку прямо сейчас — вызови KanbanStart с текстом задачи.", name),
	})
	return data
}

// repeatCallResult — ответ на N+1-й одинаковый вызов: инструмент не
// выполняется повторно (результат не изменится), модели предписывается закончить
// ход — ответить пользователю или завести эпик.
func (a *Assistant) repeatCallResult(name string, n int) []byte {
	data, _ := json.Marshal(map[string]any{
		"status": "skipped",
		"tool":   name,
		"message": fmt.Sprintf("Инструмент %s уже вызван %d раз(а) с теми же аргументами в этом ходе — "+
			"повторный вызов не даст нового результата, поэтому он не выполнен. Не перечитывай один и тот же "+
			"файл и не повторяй тот же вызов по кругу. Закончи ход: ответь пользователю по тому, что уже "+
			"выяснил, либо (если нужна правка проекта) вызови BoardCreateEpic с task_id/title/description.", name, n-1),
	})
	return data
}

// AddTools дополняет набор инструментов ассистента. Используется сервером
// (Ф-3) для инъекции мостов-инструментов к серверным git/канбан-действиям
// (KanbanStart/TaskMerge/EpicRelease/BranchReject), которые не могут жить в
// общем реестре tools из-за цикла импортов (tools → server).
func (a *Assistant) AddTools(extra ...tools.Tool) {
	a.Tools.Add(extra...)
}
