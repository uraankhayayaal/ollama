// Общие фрагменты системного промпта о токено-эффективной работе с утилитой
// Run (см. docs/PLAN-2026-09-19-todo-bash.md, Ф-2).
//
// Текст вынесен в константы, чтобы правило не расходилось между агентами и
// проверялось тестами. Фрагменты упоминают ТОЛЬКО те инструменты, которые
// реально есть у агента: RunTokenEconomy — агентам с инструментом Run
// (backend/frontend-разработчик, QA-инженер, DevOps-инженер), а
// LSPGrepFallback — только агентам с LSP/CodeSearch (разработчик). Агенты без
// Bash-инструмента (лиды, архитектор, чат-ассистент) получают Run-фрагмент
// только в связке с Kanban-декомпозицией задач для исполнителя, если
// оркестратор это делает.

// RunTokenEconomy — правила компактного вывода для агентов, у которых есть
// инструмент Run (запуск команд). Формулировки подобраны так, чтобы не
// обещать инструментов, которых у агента нет: чтение файлов — ReadFiles
// (в том числе диапазон строк), структура — List.
const RunTokenEconomy = `
### КОМПАКТНЫЙ ВЫВОД КОМАНД (экономия токенов модели — критично):
Вывод каждой команды через Run попадает в контекст целиком, поэтому:
1. Запускай проверки с компактными флагами: pytest -q, npm test -- --silent, npm test -- --silent --reporter=dot, go test ./... (БЕЗ -v), make test / make lint. Флаги -v/--verbose включают построчный лог всего прогона — не используй их, если не ищешь конкретный упавший тест.
2. Длинный вывод фильтруй: "... 2>&1 | tail -40", "| grep -E 'FAIL|Error' -A 3", "| head -60". Если нужен только факт успеха, оставь одну строку: "... > /dev/null && echo OK" (или вывод кода возврата). Фильтруй пайпом, а не проси полный лог.
3. Git-контекст вместо чтения всех файлов подряд: git log -n 3 --oneline -- путь/файла и git blame -L 10,20 путь/файла — 3 строки вместо чтения файла целиком; так видно, кто и зачем менял этот участок.
4. НЕ используй Run для чтения файлов и поиска по ним (cat/head/grep -r): у тебя для этого есть ReadFiles (в том числе диапазон строк "lines") и List. Вывод команды, который не помещается в лимит, обрезается — если тебе нужен хвост лога, добавь | tail или | tail -n 60.
5. В отчёте по задаче указывай, что запускал, и результат (exit-код/«зелёно»), а не пересказывай весь лог.`

// LSPGrepFallback — дополнение к RunTokenEconomy для агентов с
// LSP-инструментами и CodeSearch: точечный grep через Run допустим только
// когда структурированные инструменты вернули status skipped.
const LSPGrepFallback = `
6. Если LspDefinition/LspReferences/LspHover или CodeSearch вернули status skipped (индекс не построен, чекер/эмбеддинги недоступны) — точечный поиск через Run: grep -rnw --exclude-dir={node_modules,.git,dist,vendor} "символ" . (флаги -w и --exclude-dir обязательны). Это запасной путь: при работающем LSP/CodeSearch grep не нужен, а сплошной поиск по дереву (grep -r без исключений) запрещён.`
