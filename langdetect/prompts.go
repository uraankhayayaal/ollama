package langdetect

import "fmt"

// ReviewPrompt возвращает системный промпт для код-ревью на определённом
// языке. Если язык не поддерживается, возвращается универсальный промпт.
// detLang — язык, определённый по диффу; framework — необязательное имя
// фреймворка (например "Laravel"), чтобы усилить промпт для известных стеков.
func ReviewPrompt(detLang Language, framework string) string {
	// Начинаем с общей рамки код-ревью, единой для всех языков.
	base := commonReviewExcerpt(framework)

	switch detLang {
	case PHP:
		return base + phpExcerpt()
	case Go:
		return base + goExcerpt()
	case Python:
		return base + pythonExcerpt()
	case TypeScript, JavaScript:
		return base + tsJsExcerpt()
	case Java:
		return base + javaExcerpt()
	case CSharp:
		return base + csharpExcerpt()
	case SQL:
		return base + sqlExcerpt()
	case GraphQL:
		return base + graphqlExcerpt()
	case Rust:
		return base + rustExcerpt()
	default:
		return base
	}
}

// commonReviewExcerpt — универсальная часть промпта: правила оформления
// комментариев, использование инструментов, общие принципы качества.
func commonReviewExcerpt(framework string) string {
	var fw string
	if framework != "" {
		fw = fmt.Sprintf(" Стек: %s. Проверяй код с учётом идиом и лучших практик этого стека.", framework)
	}

	return fmt.Sprintf(`Ты — опытный ведущий разработчик.%s
		Твоя задача — провести качественное код-ревью изменений.
		Найди баги, проблемы безопасности, узкие места производительности и дефекты,
		оставь комментарии к конкретным строкам.
		Комментарии начинай со слов 'для заметки:' (мелкие баги или улучшения, не блокирующие запуск)
		или 'критично:' (критические ошибки, явное нарушение работы приложения или безопасности).
		ВАЖНО: результат ревью передаёшь ТОЛЬКО через вызовы инструментов, а не текстом в ответе.
		Каждое замечание — это вызов инструмента 'ReviewMr' с параметрами file_path, line, text.
		НЕ пиши текст ревью в поле ответа: такие ответы игнорируются и не попадают в MR.
		Номера строк (line) указывай ТОЧНО, каким они идут в диффе, без символа '~' и без приближений.
		Одобряй изменения инструментом 'ApproveMr', если нет критических ошибок.
		Проверяй код на соответствие принятому руководству по стилю кодирования для его языка.
		Проверяй соблюдение принципов проектирования SOLID, DRY, KISS, YAGNI.
		Проверяй обработку ошибок, edge-cases и граничные значения.
`, fw)
}

// phpExcerpt — специфика PHP/Laravel. Содержит все прежние правила проекта.
func phpExcerpt() string {
	return `
		Проверить код на соответствие руководства по стилю кодирования PSR-12.
		Проверить код на соблюдение патернов проектирования SOLID, DRY, KISS.
		Для файлов с расширением .graphql проверять систаксис и логику согласно библиотеки laravel lighthouse.
		В ресолверах ./Resolvers не должно быть бизнес логики, они должны вызывать метод batchLoader-а или сервиса.
		В запросах графкуль ./Queries, мутациях ./Mutatioins не должно быть бизнес логики, они должны вызывать метод сервиса.
		В батчлоадерах ./Batch сложная логика для оптимизации запросов, решения проблемы N+1, кэширования по тэгам, задча сделать один общий запрос к БД, и максимально всю работу закэшировать.
		Бизнес логика приложения должна быть определена и описана в сервисах, папка ./serices.
		Используются репозиотрии ./repositories, они имеют статические методы, чтобы импользовать в разных частях приложения без внедрения зависимостей.
		Используются клиенты ./clients, они совершают соединение в другие сервисы (свои и сторонние) их публичные методы должны возвращать DTO объекты.
		Используются DTO ./DTO, они описываю те данные которые не описывают модели (Model), Являются контрактами между разными частями сервиса и внешними сервисами.
		Если класс не имеет более одной зависимости и сложно реализации, то ипредпочтительно импользовать автобиндинг laravel, без лишнего объявления в dic.
		В проекте используется laravel octane swoole, проверять регистрацию клаассов, singltone, scope, bind.
		Проверять что нет статических переменных или свойств, которые нарушали бы работу swoole.
		Если Разработчик указывает константные значение, типа констант в классе, перменных окружения, конфиге, без орфографических ошибок, то довреять ему и не предлагать убедиться в правильности.
	`
}

