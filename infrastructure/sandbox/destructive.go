package sandbox

// destructive.go — отбраковка разрушительных команд ДО запуска (Ф-4).
//
// Таблица живёт в пакете sandbox (а не tools), потому что её проверяют оба
// исполнителя: локальный и контейнерный (DockerWorkspace.Run). Правила
// перенесены сюда из tools/destructive.go без изменений; tools оставил
// одноимённую обёртку для прежних вызовов и тестов.
//
// Песочница не спасает от rm -rf внутри рабочего каталога: он смонтирован на
// файловую систему хоста, и команда удалит файлы проекта по-настоящему. А
// «rm -rf /» внутри контейнера при этом вполне безобидна — то есть опасность
// команды зависит от того, где она выполнится, а не от самой команды.
//
// Здесь — только явные однозначные разрушители, а не эвристика «строка похожа на
// опасную». Причина в том, что ложное срабатывание хуже пропуска: агент
// отказался выполнить `rm -rf node_modules` перед сборкой и застрял. Всё
// сомнительное (curl | sh, sudo, chmod -R 777 /, dd, mkfs, git push --force)
// сознательно НЕ блокируется: это либо нужно по заданию, либо безопасно внутри
// песочницы, либо требует человека.

import "strings"

// destructiveCommand — команда, которую нельзя выполнять ни на хосте, ни в
// песочнице: указывает на разрушение проектных данных или системы.
type destructiveCommand struct {
	// reason — объяснение модели: что именно запрещено и что делать вместо.
	reason string
	// any — фрагменты, любой из которых означает запрет. Только точные строки,
	// НЕ отдельные слова: правило «rm + -r + /» срабатывало на
	// `rm -rf ./backend/tmp`, и агент не мог почистить каталог.
	any []string
}

