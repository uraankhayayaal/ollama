// DestructiveReason возвращает причину запрета, если команда
// разрушительна. Пустая строка — команда разрешена (песочница и правила
// ничего не сработали).
//
// Сравнение по НИЖНЕМУ регистру и с нормализацией пробелов: модель пишет
// `rm  -rf  /tmp` или `RM -RF /`, и оба варианта должны отсекаться одинаково.
func DestructiveReason(command string) (string, bool) {
	cmd := strings.ToLower(strings.TrimSpace(command))
	if cmd == "" {
		return "", false
	}
	// Нормализация: схлопываем пробелы и табуляции, чтобы `rm  -rf` совпало с
	// `rm -rf`. Пробел внутри кавычек не трогаем — для детектора это не важно.
	norm := strings.Join(strings.Fields(cmd), " ")

	for _, rule := range destructiveRules {
		for _, frag := range rule.any {
			if strings.Contains(norm, strings.ToLower(frag)) {
				return rule.reason, true
			}
		}
	}
	return "", false
}
